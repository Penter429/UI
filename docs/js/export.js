/* ============================================================
   export.js — Generate and download HTML / CSS / JS files
   ============================================================ */

/* ── Build the element tree as HTML string ── */
function buildHTMLTree(parentUid, indent, classMap) {
  const sp = '  '.repeat(indent);
  let html = '';
  const kids = childrenOf(parentUid);
  kids.forEach(d => {
    const attrs = [];
    if (d.elId) attrs.push('id="' + d.elId + '"');
    const cls = d.elClass || classMap[d.uid] || '';
    if (cls) attrs.push('class="' + cls + '"');

    // tag-specific attrs
    if (d.tag === 'img' && d.src) attrs.push('src="' + d.src + '"');
    if (d.tag === 'img' && d.alt) attrs.push('alt="' + d.alt + '"');
    if (d.tag === 'a' && d.href) attrs.push('href="' + d.href + '"');
    if (d.tag === 'input' && d.inputType) attrs.push('type="' + d.inputType + '"');
    if (['input', 'textarea'].includes(d.tag) && d.placeholder) attrs.push('placeholder="' + d.placeholder + '"');
    if (d.tag === 'iframe' && d.src) attrs.push('src="' + d.src + '"');
    if (d.tag === 'video' || d.tag === 'audio') attrs.push('controls');

    // custom attributes
    if (d.customAttrs) {
      Object.entries(d.customAttrs).forEach(([k, v]) => {
        attrs.push(k + '="' + v + '"');
      });
    }

    const attrStr = attrs.length ? ' ' + attrs.join(' ') : '';
    const voidTags = ['img', 'input', 'br', 'hr'];

    if (voidTags.includes(d.tag)) {
      html += sp + '<' + d.tag + attrStr + ' />\n';
    } else {
      const childHtml = buildHTMLTree(d.uid, indent + 1, classMap);
      if (childHtml || d.text) {
        html += sp + '<' + d.tag + attrStr + '>\n';
        if (d.text) html += sp + '  ' + d.text + '\n';
        html += childHtml;
        html += sp + '</' + d.tag + '>\n';
      } else {
        html += sp + '<' + d.tag + attrStr + '></' + d.tag + '>\n';
      }
    }
  });
  return html;
}

/* ── Generate CSS rules from all elements ── */
function buildCSS(classMap) {
  let css = '/* Generated by UI Builder */\n\n';
  css += '*, *::before, *::after { box-sizing: border-box; margin: 0; padding: 0; }\n\n';

  // body styles
  const b = App.body;
  const bodyRules = [];
  if (b.bg) bodyRules.push('background-color: ' + b.bg);
  if (b.color) bodyRules.push('color: ' + b.color);
  if (b.fontFamily) bodyRules.push('font-family: ' + b.fontFamily);
  if (b.fontSize) bodyRules.push('font-size: ' + b.fontSize + 'px');
  if (b.padding) bodyRules.push('padding: ' + b.padding);
  if (bodyRules.length) {
    css += 'body {\n  ' + bodyRules.join(';\n  ') + ';\n}\n\n';
  }

  App.elements.forEach(d => {
    let sel;
    if (d.elId) sel = '#' + d.elId;
    else if (d.elClass) sel = '.' + d.elClass.split(' ')[0];
    else sel = '.' + classMap[d.uid];

    const rules = [];
    if (!d.parentUid) {
      rules.push('position: absolute');
      rules.push('left: ' + d.x + 'px');
      rules.push('top: ' + d.y + 'px');
    }
    rules.push('width: ' + d.w + 'px');
    rules.push('height: ' + d.h + 'px');

    if (d.color) rules.push('color: ' + d.color);
    if (d.bg) rules.push('background-color: ' + d.bg);
    if (d.borderColor) rules.push('border-color: ' + d.borderColor);
    if (d.borderWidth) rules.push('border-width: ' + d.borderWidth + 'px');
    if (d.borderStyle) rules.push('border-style: ' + d.borderStyle);
    if (d.borderRadius) rules.push('border-radius: ' + d.borderRadius + 'px');
    if (d.padding) rules.push('padding: ' + d.padding);
    if (d.margin) rules.push('margin: ' + d.margin);
    if (d.fontFamily) rules.push('font-family: ' + d.fontFamily);
    if (d.fontSize) rules.push('font-size: ' + d.fontSize + 'px');
    if (d.fontWeight) rules.push('font-weight: ' + d.fontWeight);
    // layout
    if (d.display) rules.push('display: ' + d.display);
    if (d.flexDirection) rules.push('flex-direction: ' + d.flexDirection);
    if (d.justifyContent) rules.push('justify-content: ' + d.justifyContent);
    if (d.alignItems) rules.push('align-items: ' + d.alignItems);
    if (d.flexWrap) rules.push('flex-wrap: ' + d.flexWrap);
    if (d.gap) rules.push('gap: ' + d.gap);
    // advanced
    if (d.overflow) rules.push('overflow: ' + d.overflow);
    if (d.opacity !== '' && d.opacity !== undefined) rules.push('opacity: ' + d.opacity);
    if (d.zIndex) rules.push('z-index: ' + d.zIndex);
    if (d.cursor) rules.push('cursor: ' + d.cursor);
    if (d.position) rules.push('position: ' + d.position);

    css += sel + ' {\n  ' + rules.join(';\n  ') + ';\n}\n\n';
  });

  return css;
}

/* ── Build class map without mutating state ── */
function buildClassMap() {
  const map = {};
  App.elements.forEach(d => {
    if (!d.elId && !d.elClass) {
      map[d.uid] = d.uid;
    }
  });
  return map;
}

/* ── Generate full HTML page ── */
function generateFullHTML(classMap) {
  const bodyContent = buildHTMLTree(null, 2, classMap);
  return `<!DOCTYPE html>
<html lang="zh-TW">
<head>
  <meta charset="UTF-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1.0" />
  <title>My Page</title>
  <link rel="stylesheet" href="css/style.css" />
</head>
<body>
${bodyContent}  <script src="js/main.js"><\/script>
</body>
</html>`;
}

/* ── Export handlers ── */
function exportHTML() {
  const classMap = buildClassMap();
  const html = generateFullHTML(classMap);
  downloadFile('index.html', html, 'text/html');
  toast('index.html downloaded', 'success');
}

function exportCSS() {
  const classMap = buildClassMap();
  const css = buildCSS(classMap);
  downloadFile('style.css', css, 'text/css');
  toast('style.css downloaded', 'success');
}

function exportJS() {
  const js = '/* Generated by UI Builder */\n\n// Add your interactivity here\nconsole.log("Page loaded!");\n';
  downloadFile('main.js', js, 'text/javascript');
  toast('main.js downloaded', 'success');
}

/* ── Export as ZIP with folder structure ── */
function exportZIP() {
  // Check if JSZip is loaded
  if (typeof JSZip === 'undefined') {
    toast('Loading ZIP library...', 'warn');
    const script = document.createElement('script');
    script.src = 'https://cdnjs.cloudflare.com/ajax/libs/jszip/3.10.1/jszip.min.js';
    script.onload = () => doExportZIP();
    script.onerror = () => toast('Failed to load JSZip library', 'warn');
    document.head.appendChild(script);
    return;
  }
  doExportZIP();
}

function doExportZIP() {
  const classMap = buildClassMap();
  const html = generateFullHTML(classMap);
  const css = buildCSS(classMap);
  const js = '/* Generated by UI Builder */\n\n// Add your interactivity here\nconsole.log("Page loaded!");\n';

  const zip = new JSZip();
  zip.file('index.html', html);
  zip.folder('css').file('style.css', css);
  zip.folder('js').file('main.js', js);

  zip.generateAsync({ type: 'blob' }).then(blob => {
    const a = document.createElement('a');
    a.href = URL.createObjectURL(blob);
    a.download = 'my-page.zip';
    document.body.appendChild(a);
    a.click();
    setTimeout(() => { URL.revokeObjectURL(a.href); a.remove(); }, 100);
    toast('my-page.zip downloaded!', 'success');
  }).catch(err => {
    console.error('ZIP error:', err);
    toast('Failed to create ZIP', 'warn');
  });
}
